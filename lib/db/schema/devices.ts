export const devicesRelations = relations(devices, ({ one, many }) => ({
  org: one(organizations, { fields: [devices.orgId], references: [organizations.id] }),
  site: one(sites, { fields: [devices.siteId], references: [sites.id] }),
  group: one(deviceGroups, { fields: [devices.groupId], references: [deviceGroups.id] }),
  hardware: one(deviceHardware, { fields: [devices.id], references: [deviceHardware.deviceId] }),
  security: one(deviceSecurity, { fields: [devices.id], references: [deviceSecurity.deviceId] }),
  software: many(deviceSoftware),
  services: many(deviceServices),
  events: many(deviceEvents),
}));
export const deviceGroupsRelations = relations(deviceGroups, ({ one, many }) => ({
  org: one(organizations, { fields: [deviceGroups.orgId], references: [organizations.id] }),
  devices: many(devices),
}));
export const deviceSoftwareRelations = relations(deviceSoftware, ({ one }) => ({ device: one(devices, { fields: [deviceSoftware.deviceId], references: [devices.id] }) }));
export const deviceServicesRelations = relations(deviceServices, ({ one }) => ({ device: one(devices, { fields: [deviceServices.deviceId], references: [devices.id] }) }));
export const deviceEventsRelations = relations(deviceEvents, ({ one }) => ({ device: one(devices, { fields: [deviceEvents.deviceId], references: [devices.id] }) }));
