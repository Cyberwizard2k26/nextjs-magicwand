/** Dynamic group filter: a small JSON query language evaluated server-side (see lib/services/device-filter.ts). */
export interface DeviceFilter {
  all?: DeviceFilterClause[];
  any?: DeviceFilterClause[];
}
export interface DeviceFilterClause {
  field: string;
  op: "eq" | "neq" | "contains" | "startsWith" | "gt" | "lt" | "gte" | "lte" | "in" | "exists" | "regex";
  value?: unknown;
}

